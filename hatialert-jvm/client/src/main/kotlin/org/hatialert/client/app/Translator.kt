package org.hatialert.client.app

import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive

/** The app's languages, as the web app's switch (English is written in the code). */
enum class Language(val label: String) {
    ENGLISH("English"),
    NAGAMESE("Nagamese");

    companion object {
        fun fromName(name: String?): Language = entries.firstOrNull { it.name == name } ?: ENGLISH
    }
}

/**
 * Swaps English interface text for another language the way the web app does
 * (web-ts/src/i18n/translate.ts): an exact phrase first, then the first pattern
 * that matches the whole text, with each `{n}` filled by the n-th captured part
 * (itself translated when it is a known phrase); anything else stays in English.
 * Leading and trailing spaces are kept. Text people typed, names and report
 * numbers must not be passed in.
 *
 * The Nagamese table comes from the web app (`nagamese.json`, generated by
 * tools/gen_nagamese.py) and is a draft no native speaker has checked yet.
 */
class Translator(private val words: Map<String, String>, patterns: List<Pair<String, String>>) {
    private val patterns: List<Pair<Regex, String>> = patterns.map { (re, tpl) -> Regex(re) to tpl }

    /** True when every text comes back unchanged (English). */
    val isIdentity: Boolean get() = words.isEmpty() && patterns.isEmpty()

    fun tr(text: String): String {
        if (isIdentity) return text
        val s = text.trim()
        if (s.isEmpty()) return text
        val out = translateTrimmed(s) ?: return text
        val lead = text.length - text.trimStart().length
        val trail = text.length - text.trimEnd().length
        return text.substring(0, lead) + out + text.substring(text.length - trail)
    }

    /** Whether [text] has a translation (exact or by pattern); for coverage checks. */
    fun knows(text: String): Boolean = text.trim().let { it.isNotEmpty() && translateTrimmed(it) != null }

    private fun translateTrimmed(s: String): String? {
        words[s]?.let { return it }
        for ((re, tpl) in patterns) {
            val m = re.matchEntire(s) ?: continue
            return PLACEHOLDER.replace(tpl) { ph ->
                val k = ph.groupValues[1].toInt()
                tr(m.groups[k]?.value ?: "")
            }
        }
        return null
    }

    companion object {
        private val PLACEHOLDER = Regex("""\{(\d)\}""")

        val ENGLISH = Translator(emptyMap(), emptyList())

        /** Parses the phrase book JSON written by tools/gen_nagamese.py. */
        fun parse(json: String): Translator {
            val root = Json.parseToJsonElement(json).jsonObject
            val words = (root["words"] as? JsonObject ?: JsonObject(emptyMap())).mapValues { it.value.jsonPrimitive.content }
            val patterns = (root["patterns"] as? JsonArray ?: JsonArray(emptyList())).map { p ->
                val pair = p.jsonArray
                pair[0].jsonPrimitive.content to pair[1].jsonPrimitive.content
            }
            return Translator(words, patterns)
        }

        /** The Nagamese table bundled in this library (`/nagamese.json`), read once. */
        val nagamese: Translator by lazy {
            val text = Translator::class.java.getResourceAsStream("/nagamese.json")?.use { it.readBytes().toString(Charsets.UTF_8) }
                ?: error("nagamese.json is missing from the client library")
            parse(text)
        }

        fun forLanguage(language: Language): Translator = when (language) {
            Language.ENGLISH -> ENGLISH
            Language.NAGAMESE -> nagamese
        }
    }
}
